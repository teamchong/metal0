    table[0xED] = 0x00ED; // LATIN SMALL LETTER I WITH ACUTE
    table[0xEE] = 0x00EE; // LATIN SMALL LETTER I WITH CIRCUMFLEX
    table[0xEF] = 0x00EF; // LATIN SMALL LETTER I WITH DIAERESIS
