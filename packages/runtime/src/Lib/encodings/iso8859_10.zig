//! Python 'iso8859-10' Codec (ISO-8859-10 / Latin-6)
//!
//! Nordic languages (better coverage than Latin-4)
//!
//! Mirrors: CPython Lib/encodings/iso8859_10.py

const std = @import("std");
const charmap = @import("charmap.zig");

pub const name = "iso8859-10";
pub const aliases = [_][]const u8{ "iso-8859-10", "latin6", "l6", "iso_8859_10" };

/// ISO-8859-10 decode table
const decode_table: [256]u21 = blk: {
    var table: [256]u21 = undefined;
    // 0x00-0x9F same as Latin-1
    for (0..0xA0) |i| table[i] = @intCast(i);
    // 0xA0-0xFF
    table[0xA0] = 0x00A0; // NO-BREAK SPACE
    table[0xA1] = 0x0104; // LATIN CAPITAL LETTER A WITH OGONEK
    table[0xA2] = 0x0112; // LATIN CAPITAL LETTER E WITH MACRON
    table[0xA3] = 0x0122; // LATIN CAPITAL LETTER G WITH CEDILLA
    table[0xA4] = 0x012A; // LATIN CAPITAL LETTER I WITH MACRON
    table[0xA5] = 0x0128; // LATIN CAPITAL LETTER I WITH TILDE
    table[0xA6] = 0x0136; // LATIN CAPITAL LETTER K WITH CEDILLA
    table[0xA7] = 0x00A7; // SECTION SIGN
    table[0xA8] = 0x013B; // LATIN CAPITAL LETTER L WITH CEDILLA
    table[0xA9] = 0x0110; // LATIN CAPITAL LETTER D WITH STROKE
    table[0xAA] = 0x0160; // LATIN CAPITAL LETTER S WITH CARON
    table[0xAB] = 0x0166; // LATIN CAPITAL LETTER T WITH STROKE
    table[0xAC] = 0x017D; // LATIN CAPITAL LETTER Z WITH CARON
    table[0xAD] = 0x00AD; // SOFT HYPHEN
    table[0xAE] = 0x016A; // LATIN CAPITAL LETTER U WITH MACRON
    table[0xAF] = 0x014A; // LATIN CAPITAL LETTER ENG
    table[0xB0] = 0x00B0; // DEGREE SIGN
    table[0xB1] = 0x0105; // LATIN SMALL LETTER A WITH OGONEK
    table[0xB2] = 0x0113; // LATIN SMALL LETTER E WITH MACRON
    table[0xB3] = 0x0123; // LATIN SMALL LETTER G WITH CEDILLA
    table[0xB4] = 0x012B; // LATIN SMALL LETTER I WITH MACRON
    table[0xB5] = 0x0129; // LATIN SMALL LETTER I WITH TILDE
    table[0xB6] = 0x0137; // LATIN SMALL LETTER K WITH CEDILLA
    table[0xB7] = 0x00B7; // MIDDLE DOT
    table[0xB8] = 0x013C; // LATIN SMALL LETTER L WITH CEDILLA
    table[0xB9] = 0x0111; // LATIN SMALL LETTER D WITH STROKE
    table[0xBA] = 0x0161; // LATIN SMALL LETTER S WITH CARON
    table[0xBB] = 0x0167; // LATIN SMALL LETTER T WITH STROKE
    table[0xBC] = 0x017E; // LATIN SMALL LETTER Z WITH CARON
    table[0xBD] = 0x2015; // HORIZONTAL BAR
    table[0xBE] = 0x016B; // LATIN SMALL LETTER U WITH MACRON
    table[0xBF] = 0x014B; // LATIN SMALL LETTER ENG
    table[0xC0] = 0x0100; // LATIN CAPITAL LETTER A WITH MACRON
