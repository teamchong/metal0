/// Python fileinput module - Iterate over lines from multiple input streams
/// MIGRATED TO ZIGBUILDER
const std = @import("std");
const h = @import("mod_helper.zig");
const builder_mod = @import("codegen.builder");
const ast = @import("analysis.ast");

pub const Funcs = std.StaticStringMap(h.H).initComptime(.{
    .{ "input", genInput },
    .{ "filename", genFilename },
    .{ "fileno", genFileno },
    .{ "lineno", genLineno },
    .{ "filelineno", genFilelineno },
    .{ "isfirstline", genIsfirstline },
    .{ "isstdin", genIsstdin },
    .{ "nextfile", genNextfile },
    .{ "close", genClose },
    .{ "FileInput", genFileInput },
    .{ "hook_compressed", genHookCompressed },
    .{ "hook_encoded", genHookEncoded },
});

fn genInput(self: *h.NativeCodegen, _: []ast.Node) h.CodegenError!void {
    const b = try self.getBuilder();
    try b.emitValue(builder_mod.ZigValue.raw(".{ .files = &[_][]const u8{}, .inplace = false, .backup = \"\", .mode = \"r\" }"), builder_mod.EmitConfig.forExpression());
}

fn genFilename(self: *h.NativeCodegen, _: []ast.Node) h.CodegenError!void {
    const b = try self.getBuilder();
    try b.emitValue(builder_mod.ZigValue.string(""), builder_mod.EmitConfig.forExpression());
}

