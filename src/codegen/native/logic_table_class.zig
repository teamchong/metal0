/// @logic_table class code generation
///
/// The @logic_table decorator marks a class for special output format.
/// All Python syntax is handled by metal0's existing codegen infrastructure.
///
/// Example input:
/// ```python
/// @logic_table
/// class VectorOps:
///     def cosine_sim(self):
///         dot = sum(query.embedding * docs.embedding)
///         return dot / (norm(query.embedding) * norm(docs.embedding))
/// ```
///
/// Generated output:
/// ```zig
/// pub const VectorOps = struct {
///     pub const __logic_table__ = true;
///     pub fn cosine_sim(...) { ... }  // Generated by existing genFunctionDef
///     pub const methods = [_][]const u8{ "cosine_sim" };
/// };
/// // C-callable wrappers for external linking
/// export fn VectorOps_cosine_sim(...) callconv(.C) f64 {
///     return VectorOps.cosine_sim(...);
/// }
/// ```

const std = @import("std");
const ast = @import("analysis.ast");
const NativeCodegen = @import("main.zig").NativeCodegen;
const CodegenError = @import("main.zig").CodegenError;
const function_generators = @import("statements/functions/generators.zig");
const signature = @import("statements/functions/generators/signature.zig");
const gen_body = @import("statements/functions/generators/body.zig");
const function_traits = @import("analysis.function_traits");

/// Check if a class has @logic_table decorator
pub fn hasLogicTableDecorator(class: ast.Node.ClassDef) bool {
    for (class.decorators) |decorator| {
        // Check for simple name: @logic_table
        if (decorator == .name) {
            if (std.mem.eql(u8, decorator.name.id, "logic_table")) {
                return true;
            }
        }
        // Check for attribute access: @module.logic_table
        if (decorator == .attribute) {
            if (std.mem.eql(u8, decorator.attribute.attr, "logic_table")) {
                return true;
            }
        }
        // Check for call: @logic_table()
        if (decorator == .call) {
            if (decorator.call.func.* == .name) {
                if (std.mem.eql(u8, decorator.call.func.name.id, "logic_table")) {
                    return true;
                }
            }
        }
    }
    return false;
}

/// Method info for generating export wrappers
const MethodInfo = struct {
    name: []const u8,
    func: ast.Node.FunctionDef,
    needs_allocator: bool,
};

/// Generate @logic_table class as a Zig struct
/// Uses existing metal0 codegen for method bodies - no custom expression handling
pub fn genLogicTableClass(self: *NativeCodegen, class: ast.Node.ClassDef) CodegenError!void {
    const allocator = self.allocator;

    // Emit struct definition
    try self.emitIndent();
    try self.emit("pub const ");
    try self.emit(class.name);
    try self.emit(" = struct {\n");

    self.indent_level += 1;

    // Emit __logic_table__ marker
    try self.emitIndent();
    try self.emit("pub const __logic_table__ = true;\n\n");

    // Emit init function for instantiation (returns self/undefined since methods are static)
    try self.emitIndent();
    try self.emit("pub fn init(_: std.mem.Allocator) !@This() { return .{}; }\n\n");

    // Set flag so genFunctionSignature emits 'pub fn'
    self.in_logic_table_class = true;
    defer self.in_logic_table_class = false;

    // Collect method info for the methods array and export wrappers
    var methods: std.ArrayListUnmanaged(MethodInfo) = .{};
    defer methods.deinit(allocator);

    // Generate methods using existing class method codegen
    // Use genMethodSignatureWithSkip + genMethodBodyWithAllocatorInfo
    // which properly handles self parameter (as staticmethod since @logic_table methods are pure functions)
    for (class.body) |stmt| {
        if (stmt == .function_def) {
            const method = stmt.function_def;

            // Skip __init__ and dunder methods
            if (std.mem.startsWith(u8, method.name, "__")) continue;

            // Check if method needs allocator (for error handling, string ops, etc.)
            const needs_allocator = function_traits.analyzeNeedsAllocator(method, class.name);

            try methods.append(allocator, .{ .name = method.name, .func = method, .needs_allocator = needs_allocator });
            const actually_uses_allocator = function_traits.analyzeUsesAllocatorParam(method, class.name);

            // Set current function name for variable shadowing detection
            const prev_func_name = self.current_function_name;
            self.current_function_name = method.name;
            defer self.current_function_name = prev_func_name;

            // Generate method signature - treat as staticmethod since @logic_table methods are pure functions
            // The mutates_self=false since we don't have a real self
            // NOTE: For @logic_table, methods don't use self, so we generate them as static methods
            try signature.genMethodSignatureWithSkip(self, class.name, method, false, needs_allocator, false, actually_uses_allocator);

            // Generate method body
            try gen_body.genMethodBodyWithAllocatorInfo(self, method, needs_allocator, actually_uses_allocator);
        }
    }

    // Emit methods registry
    try self.emitIndent();
    try self.emit("pub const methods = [_][]const u8{\n");
    self.indent_level += 1;
    for (methods.items) |m| {
        try self.emitIndent();
        try self.emitFmt("\"{s}\",\n", .{m.name});
    }
    self.indent_level -= 1;
    try self.emitIndent();
    try self.emit("};\n");

    self.indent_level -= 1;
    try self.emitIndent();
    try self.emit("};\n\n");

    // Generate C-callable export wrappers at module level ONLY when --emit-logic-table is used
    // These are free functions with export linkage that call the struct methods
    std.debug.print("emit_logic_table_exports = {}\n", .{self.emit_logic_table_exports});
    if (self.emit_logic_table_exports) {
        try self.emit("// __logic_table_exports_begin__\n");
        for (methods.items) |m| {
            try genExportWrapper(self, class.name, m.name, m.func, m.needs_allocator);
        }
        try self.emit("// __logic_table_exports_end__\n");
    }
}

/// Generate a C-callable export wrapper for a struct method
/// This allows the method to be called from C/external code via dlsym
fn genExportWrapper(self: *NativeCodegen, class_name: []const u8, method_name: []const u8, func: ast.Node.FunctionDef, needs_allocator: bool) CodegenError!void {
    // Export wrapper signature: export fn ClassName_methodName(args...) callconv(.c) ReturnType
    try self.emitFmt("export fn {s}_{s}(", .{ class_name, method_name });

    // Generate parameters (skip 'self' which is the first parameter)
    var param_count: usize = 0;
    for (func.args) |arg| {
        // Skip 'self' parameter
        if (std.mem.eql(u8, arg.name, "self")) continue;

        if (param_count > 0) try self.emit(", ");

        // For simplicity, use f64 for numeric types and [*]f64 for arrays
        // This provides a C-compatible ABI
        try self.emitFmt("{s}: ", .{arg.name});
        if (arg.type_annotation) |type_name| {
            if (std.mem.eql(u8, type_name, "float")) {
                try self.emit("f64");
            } else if (std.mem.eql(u8, type_name, "int")) {
                try self.emit("i64");
            } else if (std.mem.eql(u8, type_name, "list") or std.mem.startsWith(u8, type_name, "list[")) {
                // list or list[float] -> [*]f64
                try self.emit("[*]f64");
            } else {
                try self.emit("*anyopaque"); // Generic pointer for unknown types
            }
        } else {
            // No annotation - assume f64 for numeric compatibility
            try self.emit("f64");
        }
        param_count += 1;
    }

    // If there were array parameters, add a length parameter
    var has_array_param = false;
    for (func.args) |arg| {
        if (std.mem.eql(u8, arg.name, "self")) continue;
        if (arg.type_annotation) |type_name| {
            if (std.mem.eql(u8, type_name, "list") or std.mem.startsWith(u8, type_name, "list[")) {
                has_array_param = true;
                break;
            }
        }
    }
    if (has_array_param) {
        if (param_count > 0) try self.emit(", ");
        try self.emit("len: usize");
    }

    // Return type - use .c for C calling convention
    try self.emit(") callconv(.c) ");

    // Determine return type from annotation
    if (func.return_type) |ret_type| {
        if (std.mem.eql(u8, ret_type, "float")) {
            try self.emit("f64");
        } else if (std.mem.eql(u8, ret_type, "int")) {
            try self.emit("i64");
        } else {
            try self.emit("f64"); // Default to f64
        }
    } else {
        try self.emit("f64"); // Default return type
    }

    try self.emit(" {\n");
    self.indent_level += 1;

    // Generate call to struct method
    // The struct method has signature: fn(self, [allocator], args...) !ReturnType
    // Pass undefined for self since @logic_table methods don't actually use it
    // Only pass allocator if the method needs it
    // Use catch to convert error union to plain value (return 0/NaN on error)
    try self.emitIndent();
    if (needs_allocator) {
        try self.emitFmt("return {s}.{s}(undefined, __global_allocator", .{ class_name, method_name });
    } else {
        try self.emitFmt("return {s}.{s}(undefined", .{ class_name, method_name });
    }

    // Forward parameters
    for (func.args) |arg| {
        if (std.mem.eql(u8, arg.name, "self")) continue;

        // Wrap pointer parameters in slices using length
        if (arg.type_annotation) |type_name| {
            if (std.mem.eql(u8, type_name, "list") or std.mem.startsWith(u8, type_name, "list[")) {
                try self.emitFmt(", {s}[0..len]", .{arg.name});
            } else {
                try self.emitFmt(", {s}", .{arg.name});
            }
        } else {
            try self.emitFmt(", {s}", .{arg.name});
        }
    }

    // Only use catch if method returns error union (needs_allocator implies error return)
    if (needs_allocator) {
        try self.emit(") catch 0.0;\n");
    } else {
        try self.emit(");\n");
    }

    self.indent_level -= 1;
    try self.emitIndent();
    try self.emit("}\n\n");
}

test "hasLogicTableDecorator" {
    // Test with simple decorator
    const class1 = ast.Node.ClassDef{
        .name = "Test",
        .bases = &[_][]const u8{},
        .body = &[_]ast.Node{},
        .decorators = &[_]ast.Node{
            .{ .name = .{ .id = "logic_table" } },
        },
    };
    try std.testing.expect(hasLogicTableDecorator(class1));

    // Test without decorator
    const class2 = ast.Node.ClassDef{
        .name = "Test",
        .bases = &[_][]const u8{},
        .body = &[_]ast.Node{},
        .decorators = &[_]ast.Node{},
    };
    try std.testing.expect(!hasLogicTableDecorator(class2));
}
